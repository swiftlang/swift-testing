extension Test.Case {
  /// A type describing a lazily-generated sequence of test cases generated from
  /// a known sequence of argument values.
  ///
  /// Instances of this type can be iterated over multiple times.
  ///
  /// @Comment {
  ///   - Bug: The testing library should support variadic generics.
  ///     ([103416861](rdar://103416861))
  /// }
  struct Generator<S, E>: Sendable where S: Sendable & ~Copyable, E: Sendable & ~Copyable {
    /// Make an iterator over the test cases generated by this instance.
    ///
    /// - Returns: An iterator over `self`.
    private var _makeIterator: @Sendable () -> AnyIterator<Test.Case>

    /// The underestimated count of the underlying sequence or iterable.
    private var _underestimatedCount: Int

    /// Initialize an instance of this type that iterates over the specified
    /// sequence of argument values.
    ///
    /// - Parameters:
    ///   - argumentList: An argument list representing the set of argument
    ///     values for which test cases should be generated.
    ///   - parameters: The parameters of the test function for which test cases
    ///     should be generated.
    ///   - testFunction: The test function to which each generated test case
    ///     passes an argument value from `argumentList`.
    init(
      argumentList: Test.Case.Argument.List<S, E>,
      parameters: [Test.Parameter],
      testFunction: nonisolated(nonsending) @escaping @Sendable (S.Element) async throws -> Void
    ) where S: Sequence, E == S.Element {
      _makeIterator = {
        Self._makeIterator(from: argumentList) { element in
          Test.Case(values: argumentList.makeArgumentValues(element), parameters: parameters) {
            try await testFunction(element)
          }
        }
      }
      _underestimatedCount = argumentList.wrappedValue.underestimatedCount
    }

    /// Initialize an instance of this type that generates exactly one test
    /// case.
    ///
    /// - Parameters:
    ///   - testFunction: The test function called by the generated test case.
    init(
      testFunction: nonisolated(nonsending) @escaping @Sendable () async throws -> Void
    ) where S == CollectionOfOne<Void>, E == Void {
      // A beautiful hack to give us the right number of cases: iterate over a
      // collection containing a single Void value.
      let argumentList = Test.Case.Argument.List(CollectionOfOne(())) { [] }
      self.init(argumentList: argumentList, parameters: [], testFunction: testFunction)
    }

    /// Initialize an instance of this type that iterates over the specified
    /// collections of argument values.
    ///
    /// - Parameters:
    ///   - collection1: The first collection of argument values for which test
    ///     cases should be generated.
    ///   - collection2: The second collection of argument values for which test
    ///     cases should be generated.
    ///   - parameters: The parameters of the test function for which test cases
    ///     should be generated.
    ///   - testFunction: The test function to which each generated test case
    ///     passes an argument value from the Cartesian product of `collection1`
    ///     and `collection2`.
    ///
    /// - Bug: The testing library should support variadic generics.
    ///     ([103416861](rdar://103416861))
    init<C1, C2>(
      argumentLists collection1: Test.Case.Argument.List<C1, C1.Element>, _ collection2: Test.Case.Argument.List<C2, C2.Element>,
      parameters: [Test.Parameter],
      testFunction: nonisolated(nonsending) @escaping @Sendable ((C1.Element, C2.Element)) async throws -> Void
    ) where S == CartesianProduct<C1, C2>, E == (C1.Element, C2.Element) {
      let cartesianProduct = Test.Case.Argument.List(cartesianProduct(collection1.wrappedValue, collection2.wrappedValue)) { element in
        collection1.makeArgumentValues(element.0) + collection2.makeArgumentValues(element.1)
      }
      self.init(argumentList: cartesianProduct, parameters: parameters, testFunction: testFunction)
    }

    /// Initialize an instance of this type that iterates over the specified
    /// inline array of argument values.
    ///
    /// - Parameters:
    ///   - argumentList: An argument list representing the set of argument
    ///   	values for which test cases should be generated.
    ///   - parameters: The parameters of the test function for which test cases
    ///     should be generated.
    ///   - testFunction: The test function to which each generated test case
    ///     passes an argument value from `argumentList`.
    @available(_inlineArrayAPI, *)
    init<let count: Int>(
      argumentList: consuming Test.Case.Argument.List<S, E>,
      parameters: [Test.Parameter],
      testFunction: nonisolated(nonsending) @escaping @Sendable (borrowing E) async throws -> Void
    ) where S == InlineArray<count, E> {
      _underestimatedCount = argumentList.wrappedValue.underestimatedCount
      _makeIterator = { [argumentList = consume argumentList] in
        Self._makeIterator(in: 0 ..< count) { i in
          let values = argumentList.makeArgumentValues(argumentList.wrappedValue[i])
          return Test.Case(values: values, parameters: parameters) {
            try await testFunction(argumentList.wrappedValue[i])
          }
        }
      }
    }

    /// Initialize an instance of this type that iterates over the specified
    /// inline array of argument values.
    ///
    /// - Parameters:
    ///   - argumentList1: The first argument list.
    ///   - argumentList2: The second argument list.
    ///   - parameters: The parameters of the test function for which test cases
    ///     should be generated.
    ///   - testFunction: The test function to which each generated test case
    ///     passes an argument value from the Cartesian product of
    ///     `argumentList1` and `argumentList2`.
    @available(_inlineArrayAPI, *)
    init<let count1: Int, E1, let count2: Int, E2>(
      argumentLists argumentList1: consuming Test.Case.Argument.List<InlineArray<count1, E1>, E1>, _ argumentList2: consuming Test.Case.Argument.List<InlineArray<count2, E2>, E2>,
      parameters: [Test.Parameter],
      testFunction: nonisolated(nonsending) @escaping @Sendable (borrowing E1, borrowing E2) async throws -> Void
    ) where S == CartesianProduct<Range<Int>, Range<Int>>, E == S.Element, E1: Sendable & ~Copyable, E2: Sendable & ~Copyable {
      let argumentList1 = Allocated(consume argumentList1)
      let argumentList2 = Allocated(consume argumentList2)
      let cartesianProduct = Test.Case.Argument.List(
        cartesianProduct(0 ..< count1, 0 ..< count2)
      ) { i1, i2 in
        argumentList1.value.makeArgumentValues(argumentList1.value.wrappedValue[i1]) + argumentList2.value.makeArgumentValues(argumentList2.value.wrappedValue[i2])
      }
      self.init(argumentList: cartesianProduct, parameters: parameters) { i1, i2 in
        try await testFunction(argumentList1.value.wrappedValue[i1], argumentList2.value.wrappedValue[i2])
      }
    }
  }
}

// MARK: - Sequence

extension Test.Case.Generator: Sequence where S: ~Copyable, E: ~Copyable {
  func makeIterator() -> some IteratorProtocol<Test.Case> {
    _makeIterator()
  }

  var underestimatedCount: Int {
    _underestimatedCount
  }

  /// Make a copy of the given test case with its ID's `discriminator` property
  /// set to a locally unique value.
  ///
  /// - Parameters:
  /// 	- testCase: The test case to make a copy of.
  ///   - testCaseIDs: Storage for test case IDs and their discriminators in the
  ///   	sequence of test cases currently being iterated.
  ///
  /// - Returns: A copy of `testCase` with its ID's `discriminator` property set
  /// 	to a locally unique value.
  private static func _discriminateTestCase(_ testCase: Test.Case, testCaseIDs: inout [Test.Case.ID: Int]) -> Test.Case {
    var testCase = testCase

    if testCase.isParameterized {
      // Store the original, unmodified test case ID. We're about to modify a
      // property which affects it, and we want to update state based on the
      // original one.
      let testCaseID = testCase.id

      // Ensure test cases with identical IDs each have a unique discriminator.
      let discriminator = testCaseIDs[testCaseID, default: 0]
      testCase.discriminator = discriminator
      testCaseIDs[testCaseID] = discriminator + 1
    }

    return testCase
  }
}

extension Test.Case.Generator where S: Sequence, E == S.Element {
  /// Make an iterator over the given argument list that produces test cases for
  /// each element thereof.
  ///
  /// - Parameters:
  /// 	- argumentList: The argument list to iterate over.
  ///   - mapElement: A function that maps an element from `argumentList` to an
  ///   	instance of ``Test/Case``.
  ///
  /// - Returns: An iterator over `argumentList`.
  ///
  /// This overload is used when `S` conforms to ``Sequence``.
  private static func _makeIterator(
    from argumentList: Test.Case.Argument.List<S, E>,
    mappingElementWith mapElement: @escaping (borrowing E) -> Test.Case
  ) -> AnyIterator<Test.Case> {
    let state = (
      iterator: argumentList.wrappedValue.makeIterator(),
      testCaseIDs: [Test.Case.ID: Int](minimumCapacity: argumentList.wrappedValue.underestimatedCount)
    )

    return AnyIterator(
      sequence(state: state) { state in
        guard let element = state.iterator.next() else {
          return nil
        }
        return _discriminateTestCase(mapElement(element), testCaseIDs: &state.testCaseIDs)
      }
    )
  }
}

@available(_inlineArrayAPI, *)
extension Test.Case.Generator where S: ~Copyable, E: ~Copyable {
  /// Make an iterator over the given `0`-based indices that produces test cases
  /// for each index therein.
  ///
  /// - Parameters:
  ///   - range: The range of `0`-based indices to iterate over.
  ///   - mapElementAtIndex: A function that maps an index from `range` to an
  ///     instance of ``Test/Case``.
  ///
  /// - Returns: An iterator over `range`.
  ///
  /// This overload is used when `S` does not conform to ``Sequence`` and when
  /// its elements must be referenced by index rather than being copied.
  private static func _makeIterator(
    in range: Range<Int>,
    mappingElementAtIndexWith mapElementAtIndex: @escaping (Int) -> Test.Case
  ) -> AnyIterator<Test.Case> {
    var testCaseIDs = [Test.Case.ID: Int](minimumCapacity: range.count)
    return AnyIterator(
      range.lazy.map { i in
        _discriminateTestCase(mapElementAtIndex(i), testCaseIDs: &testCaseIDs)
      }.makeIterator()
    )
  }
}
